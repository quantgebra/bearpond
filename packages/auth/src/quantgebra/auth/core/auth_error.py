from typing import Literal

AuthErrorKind = Literal[
    "invalid_request",
    "invalid_credentials",
    "invalid_invite",
    "weak_password",
    "throttled",
    "disabled",
    "forbidden",
    "unauthenticated",
]


# ======================================================================================================================
class AuthError(Exception):

    # ==================================================================================================================
    # CLASS
    # ==================================================================================================================

    # ==================================================================================================================
    # INSTANCE
    # ==================================================================================================================

    # ------------------------------------------------------------------------------------------------------------------
    def __init__(self, kind: AuthErrorKind, message: str) -> None:
        super().__init__(message)
        self.kind: AuthErrorKind = kind
        self.message: str = message
